-- STEP 2 — public.cards (7,142 rows: 333 assigned + 6,809 unassigned)
-- =============================================================================
--   cardid -> card_code, copied unchanged. §2.2/Q1 established that the 48-bit
--     hex suffix IS the card secret and that all 7,142 are unique, so
--     regenerating codes would invalidate physical inventory for no gain.
--     Re-verified against the export before loading: every suffix is exactly 12
--     hex characters and all 7,142 are distinct.
--
--   cardstatus -> status. The 0/1 -> unassigned/assigned mapping was NOT
--     assumed from the column name; it was checked against the data. The
--     generator asserts, for all 7,142 rows, that `cardstatus = '1'` holds if
--     and only if `ownerid` is non-null. That is what makes the mapping a fact
--     rather than a reasonable-sounding guess — and it also proves the import
--     cannot violate `cards_assigned_requires_owner`.
--
--   ownerid -> owner_user_id, via the map join. Every one of the 333 non-null
--     owner ids resolved; 0 orphans (verified in STEP 5). 314 distinct owners.
--
-- The 6,809 unassigned rows are inserted with only (card_code, created_at,
-- legacy_card_id): `status` takes its 'unassigned' default and owner_user_id /
-- assigned_at are NULL for every one of them, so emitting those literals 6,809
-- times would add bulk without adding information.
--
-- ... 7,142 rows loaded here (see generator: `cards_assigned_*.sql`,
--     `cards_unassigned_*.sql`) ...


-- =============================================================================
-- STEP 3 — public.social_links (465 of 466 rows; 1 skipped)
-- =============================================================================
-- §6.4 says "validate/normalize URLs on the way in". The rule applied uniformly
-- to all 466 rows, and why each branch is safe:
--
--   (a) Already a single well-formed http(s) URL with no whitespace -> imported,
--       with the scheme lowercased. URI schemes are case-insensitive (RFC 3986
--       §3.1) and lowercase is the specified normal form, so `Https://` ->
--       `https://` cannot change which resource is addressed. 1 row (legacy
--       sociallink id 403) needed this.
--
--   (b) Contains whitespace but exactly ONE http(s) token -> that token is
--       taken. Whitespace terminates a URL in every parser, so the trailing
--       words were never part of the link and nothing is discarded. 7 rows, all
--       LinkedIn (legacy ids 33, 83, 203, 213, 249, 317, 442).
--
--   (c) More than one http(s) token in free text -> SKIPPED, not guessed.
--       1 row: legacy sociallink id 85 (legacy user 37, platform Instagram).
--       Choosing one of two candidate URLs would publish a link to a real
--       person's account on a coin flip. A missing link is a visibly missing
--       link the owner can re-add; a wrong link points strangers at someone
--       else's profile and looks correct. Failing closed is the cheaper error.
--
--   http:// is deliberately NOT upgraded to https:// (4 rows). Rewriting the
--   scheme changes which resource is requested based on an assumption about a
--   remote host we do not control. That is a guess wearing a normalisation's
--   clothing.
--
--   `updateddatetime = '-infinity'` (58 rows) -> substituted with the row's own
--   created_at. `-infinity` is a Postgres sentinel, not a time: it survives the
--   column type but breaks JS `Date` parsing and cannot be rendered, so it would
--   surface as a client-side crash on a profile page. created_at is the only
--   defensible substitute — the row demonstrably existed then. The 132 ordinary
--   rows where updated < created are NOT touched: those are real timestamps,
--   they only look odd, and rewriting them would destroy true data to satisfy
--   an aesthetic expectation.
--
--   6 exact duplicate (user, platform, url) rows were imported faithfully
--   rather than de-duplicated. There is no unique constraint on that triple, so
--   the legacy state is representable; silently dropping rows during a
--   migration hides data the owner may want to clean up deliberately.
--
-- ... 465 rows loaded here (see generator: `links_*.sql`) ...


