-- =============================================================================
-- 2026-08-13_legacy_import.sql
--
-- One-time production import of the legacy SmartCard database into
-- SmartCard 2.0. Executed 2026-08-13 against project crpsbnbegeoqtlgshltt.
--
-- WHY THIS LIVES IN supabase/seed/ AND NOT supabase/migrations/
--   Migrations must be replayable from zero on any environment. This file
--   inserts 9,757 rows of *specific production data* with hard-coded primary
--   keys and unique values (`legacy_user_id`, `card_code`, `legacy_card_id`).
--   Replaying it on a fresh database that already ran it — or on a developer's
--   local stack — fails on unique-constraint violations, which would make
--   `supabase db reset` permanently broken. Schema changes belong in
--   migrations; this is operational data, and it runs exactly once.
--
--   The one genuinely structural piece of this import — the `legacy` schema and
--   the `legacy.contactexchange` table — IS a migration, and lives at
--   supabase/migrations/20260813171953_legacy_schema_contactexchange_archive.sql.
--   Only the row loading is here.
--
-- WHY THE ROW DATA IS NOT IN THIS FILE
--   The source export contains real personal data: 337 people's emails, phone
--   numbers and free-text bios, plus 1,813 captured contact records. Checking
--   9,757 rows of that into git would publish it to every clone of the repo
--   forever, including any future public one, and git history cannot be
--   un-published. This file therefore records the *transformation* — the rules,
--   the judgement calls, and the checks — which is the part a reviewer needs and
--   the part that is worth version-controlling. The rows themselves were
--   generated by the accompanying script from a local export and streamed
--   straight to the database.
--
--   To reproduce: run 2026-08-13_legacy_import_generator.py against the export,
--   then execute the emitted chunks in the order given under "LOAD ORDER".
--
-- SOURCE
--   core-data-export.sql — a Postgres COPY dump of the legacy database:
--     users            337 rows
--     card           7,142 rows
--     sociallink       466 rows
--     contactexchange 1,813 rows
-- =============================================================================


-- =============================================================================
-- STEP 0 — the legacy-id -> UUID map (temporary)
-- =============================================================================
-- Every legacy table references users by integer id. The new schema uses random
-- UUIDs. Rather than embed the mapping in each generated INSERT — where a single
-- transcription slip would silently attach a card to the wrong person — the map
-- is materialised once as a table, and every downstream insert JOINs against it.
-- A wrong id then cannot produce a wrong row: it produces no row at all, and the
-- row-count check catches it.
--
-- The UUIDs are random (uuid4), generated once and frozen, per §6.2 ("new UUID").
-- They are deliberately NOT derived from the legacy id — a derivable UUID would
-- leak the legacy id and the signup order into every public identifier.
--
-- This schema is temporary and was dropped at the end of the run (STEP 6).
-- Dropping it loses nothing: the mapping survives permanently and canonically as
-- public.users.legacy_user_id -> public.users.id, which is unique on both sides.

create schema if not exists legacy_staging;

create table legacy_staging.user_id_map (
  legacy_user_id bigint primary key,
  new_user_id    uuid   not null unique
);

