-- =============================================================================
-- STEP 1 — public.users (337 rows)
-- =============================================================================
-- Shape of every generated statement:
--
--   insert into public.users (id, kinde_user_id, email, ..., legacy_user_id, ...)
--   select m.new_user_id, v.kinde, v.email::extensions.citext, ...
--   from (values (…), (…), …) as v(legacy_id, kinde, email, …)
--   join legacy_staging.user_id_map m on m.legacy_user_id = v.legacy_id;
--
-- Note that `users` resolves its own id through the map too. That is not
-- redundancy — it is what guarantees `users.id` and the map can never disagree,
-- so cards and social_links cannot end up pointing at a user id that was never
-- inserted.
--
-- COLUMN MAPPING (per §6.2), with the decisions that §6.2 left open:
--
--   loginpassword -> DROPPED. Never selected out of the export, never written
--     to any generated file, never transmitted, never logged. The legacy bcrypt
--     hashes have no role in the new system — Kinde is the sole identity
--     provider (§5.3) — so importing them would create a credential store that
--     nothing authenticates against and everything could leak. Verified absent
--     afterwards by the sweep in STEP 5.
--
--   userstatus -> status. JUDGEMENT CALL: the export contains exactly ONE
--     distinct value across all 337 rows — '1'. There is no legacy row from
--     which a 'suspended' or 'deleted' state could be inferred, and the
--     generator asserts this (`assert set(userstatus) == {'1'}`) so the mapping
--     cannot be silently wrong if the export ever changes. '1' -> 'active'.
--     Nobody was defaulted into a restrictive state on a guess: 'suspended' and
--     'deleted' both remove access, and inventing either from an unlabelled
--     integer would lock a real person out of their own account.
--
--   profilephoto -> photo_path: LEFT NULL FOR EVERY ROW in this pass, by
--     instruction. See 2026-08-13_legacy_photo_paths.csv and §6.5 — the paths
--     are preserved there so a follow-up pass can upload the files and
--     backfill `photo_path` without re-reading the legacy database.
--
--   '' -> NULL for bio (21 rows), company_name (15), company_role (13).
--     An empty string and NULL mean the same thing here — "not filled in" — and
--     collapsing them means UI code and `coalesce` behave the same way for every
--     user instead of depending on which legacy form version they used.
--     first_name, last_name and phone_number had no empty strings to collapse.
--
--   email / username -> extensions.citext. Cast explicitly rather than left to
--     implicit coercion so a duplicate that differs only in case fails loudly
--     on the unique index at import time, not later at signup.
--
-- ... 337 rows loaded here (see generator: `users_*.sql`) ...


