-- 5a. Row counts and referential integrity.
-- Expected: 337 / 7142 / 333 / 6809 / 7142 / 465 / 1813, and 0 for every
-- "orphan"/"without"/"with" column below.
select
  (select count(*) from public.users)                                                as users_total,
  (select count(*) from public.cards)                                                as cards_total,
  (select count(*) from public.cards where status = 'assigned')                      as cards_assigned,
  (select count(*) from public.cards where status = 'unassigned')                    as cards_unassigned,
  (select count(distinct card_code) from public.cards)                               as cards_distinct_codes,
  (select count(*) from public.social_links)                                         as social_links_total,
  (select count(*) from legacy.contactexchange)                                      as contactexchange_total,
  (select count(*) from public.cards c
     where c.owner_user_id is not null
       and not exists (select 1 from public.users u where u.id = c.owner_user_id))   as orphan_card_owners,
  (select count(*) from public.social_links s
     where not exists (select 1 from public.users u where u.id = s.user_id))         as orphan_social_links,
  (select count(*) from public.cards where status = 'assigned' and owner_user_id is null)     as assigned_without_owner,
  (select count(*) from public.cards where status = 'unassigned' and owner_user_id is not null) as unassigned_with_owner,
  (select count(*) from public.users where photo_path is not null)                   as users_with_photo_path,
  (select count(*) from public.users where status <> 'active')                       as users_not_active,
  (select count(distinct legacy_user_id) from public.users)                          as distinct_legacy_user_ids;


-- 5b. No password-shaped value survives anywhere in public.users.
-- Deliberately column-agnostic: rather than checking the columns we expect to be
-- clean, this converts each row to JSON and scans EVERY text-ish value, so a
-- hash that ended up in the wrong column (e.g. pasted into `bio`) is still
-- caught. Matches bcrypt/argon2/scrypt/PBKDF2/MD5-crypt/SHA-crypt prefixes, LDAP
-- {SSHA}-style prefixes, and any long unbroken base64-ish blob.
-- Expected: 0.
select count(*) filter (where hit) as password_shaped_hits,
       count(*)                    as rows_scanned
from (
  select exists (
           select 1
           from jsonb_each_text(to_jsonb(u)) kv(k, v)
           where v ~ '^\$(2[abxy]?|1|5|6|argon2[id]{1,2}|scrypt|pbkdf2)\$'
              or v ~ '^\{(SSHA|SHA|MD5|CRYPT)\}'
              or (length(v) between 40 and 200
                  and v ~ '^[A-Za-z0-9+/._$-]+$'
                  and v !~ '[ @]'
                  and k not in ('id', 'kinde_user_id'))
         ) as hit
  from public.users u
) t;


-- 5c. Content checksum — the check that row counts cannot make.
-- The rows were hand-transmitted as SQL text, so a correct count proves nothing
-- about a mangled character inside a bio. This computes an order-independent
-- digest of the actual column values, which is compared against the identical
-- digest computed locally from the source export. They must match exactly.
--
-- Two details that make the two sides comparable:
--   * timestamps are canonicalised through to_char(... at time zone 'UTC') so
--     that '…10.585+00' and '…10.585000' are the same string on both sides;
--   * NULL gets an explicit sentinel, because ''||NULL is NULL and would
--     otherwise make an all-NULL row indistinguishable from any other.
-- `order by h collate "C"` pins byte ordering so the digest is locale-independent.
--
-- Shown here for legacy.contactexchange; the same construction was run for
-- users, cards and social_links.
-- Expected (contactexchange): aef81c1bd937ee2204ce190f4d2dad47
with rowhash as (
  select md5(
    legacy_id::text || '|~|' ||
    card_owner_legacy_user_id::text || '|~|' ||
    coalesce(sender_legacy_user_id::text, '<<NULL>>') || '|~|' ||
    coalesce(sender_name,  '<<NULL>>') || '|~|' ||
    coalesce(sender_email, '<<NULL>>') || '|~|' ||
    coalesce(sender_phone, '<<NULL>>') || '|~|' ||
    coalesce(notes,        '<<NULL>>') || '|~|' ||
    to_char(created_at at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')
  ) as h
  from legacy.contactexchange
)
select count(*) as rows, md5(string_agg(h, '' order by h collate "C")) as content_md5
from rowhash;


-- 5d. The `legacy` schema is unreachable from application code.
-- §6.7's guarantee is "not reachable from application code", and the migration
-- header claims defence in depth. This checks the depth rather than trusting the
-- schema name: even if PostgREST were reconfigured to expose `legacy`, anon and
-- authenticated have no USAGE on the schema, no SELECT on the table, and the
-- table has RLS enabled + FORCEd with zero policies.
-- Expected: false, false, false, false, true, true, 0, 1.
select
  has_schema_privilege('anon',          'legacy', 'USAGE')                    as anon_schema_usage,
  has_schema_privilege('authenticated', 'legacy', 'USAGE')                    as auth_schema_usage,
  has_table_privilege ('anon',          'legacy.contactexchange', 'SELECT')   as anon_select,
  has_table_privilege ('authenticated', 'legacy.contactexchange', 'SELECT')   as auth_select,
  (select relrowsecurity      from pg_class where oid = 'legacy.contactexchange'::regclass) as rls_enabled,
  (select relforcerowsecurity from pg_class where oid = 'legacy.contactexchange'::regclass) as rls_forced,
  (select count(*) from pg_policies where schemaname = 'legacy')              as policies_on_legacy,
  (select count(*) from information_schema.tables where table_schema = 'legacy') as tables_in_legacy;

-- And: no `pgrst.*` GUC is persisted anywhere in this database, so PostgREST is
-- running on the project's configured exposed-schema list and nothing in this
-- import added `legacy` to it. Expected: zero rows from the first branch.
select coalesce(d.datname, '(all databases)') as database,
       coalesce(r.rolname, '(all roles)')     as role,
       s.setconfig
from pg_db_role_setting s
left join pg_database d on d.oid = s.setdatabase
left join pg_roles    r on r.oid = s.setrole
where exists (select 1 from unnest(s.setconfig) c where c like 'pgrst.%');


-- 5e. Linkage proof — run BEFORE dropping legacy_staging, since this is the last
-- moment the map exists to be checked against.
-- Expected: 337, 337, 0, 0, 314, 0, 0, 0, 0.
select
  (select count(*) from legacy_staging.user_id_map)                                   as map_rows,
  (select count(*) from legacy_staging.user_id_map m
     join public.users u on u.legacy_user_id = m.legacy_user_id
    where u.id = m.new_user_id)                                                       as users_matching_map,
  (select count(*) from public.users u
     where not exists (select 1 from legacy_staging.user_id_map m
                        where m.legacy_user_id = u.legacy_user_id))                   as users_not_in_map,
  (select count(*) from legacy_staging.user_id_map m
     where not exists (select 1 from public.users u
                        where u.legacy_user_id = m.legacy_user_id))                   as map_entries_without_user,
  (select count(distinct owner_user_id) from public.cards where owner_user_id is not null) as distinct_card_owners,
  (select count(*) from public.cards c
     where c.owner_user_id is not null
       and not exists (select 1 from legacy_staging.user_id_map m
                        where m.new_user_id = c.owner_user_id))                       as card_owners_off_map,
  (select count(*) from public.social_links s
     where not exists (select 1 from legacy_staging.user_id_map m
                        where m.new_user_id = s.user_id))                             as social_links_off_map,
  (select count(*) from legacy.contactexchange x
     where not exists (select 1 from public.users u
                        where u.legacy_user_id = x.card_owner_legacy_user_id))        as cx_unresolvable_owners,
  (select count(*) from legacy.contactexchange x
     where x.sender_legacy_user_id is not null
       and not exists (select 1 from public.users u
                        where u.legacy_user_id = x.sender_legacy_user_id))            as cx_unresolvable_senders;


